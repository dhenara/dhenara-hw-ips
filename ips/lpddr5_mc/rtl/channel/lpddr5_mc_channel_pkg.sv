  function automatic logic [13:0] ca_pack(input logic [6:0] rise, fall);
    return {fall, rise};
  endfunction
  function automatic logic [13:0] ca_activate(input logic [17:0] row, input logic [3:0] bank, input logic second);
    return second ? ca_pack({row[10:7],3'b011},row[6:0])
                  : ca_pack({row[17:14],3'b111},{row[13:11],bank});
  endfunction
  function automatic logic [13:0] ca_access(input logic write_access, bl32, masked,
      input logic [3:0] bank, input logic [5:0] column, input logic ap);
    logic [2:0] opcode;
    opcode = masked ? 3'd2 : bl32 ? (write_access ? 3'd4 : 3'd5) : (write_access ? 3'd6 : 3'd1);
    return ca_pack({column[5:3],column[0],opcode},{ap,column[2:1],bank});
  endfunction
  function automatic logic [13:0] ca_cas(input logic [2:0] ws);
    return ca_pack({ws,4'b1100},7'b0);
  endfunction
  function automatic logic [13:0] ca_maintenance(input logic precharge, rfm, all_banks, input logic [3:0] bank);
    return ca_pack(precharge ? 7'd120 : 7'd56,{all_banks,2'b0,(bank[3]|rfm),bank[2:0]});
  endfunction
  function automatic logic [13:0] ca_mrw(input logic [6:0] address, input logic [7:0] value, input logic second);
    return second ? ca_pack({value[7],6'd8},value[6:0]) : ca_pack(7'd88,address);
  endfunction
  function automatic logic [31:0] maintenance_admission_budget(input lpddr5_mc_profile_t p,input logic per_bank);
    logic [31:0] reserve_value;
    logic unused_profile;
    unused_profile=^p;
    reserve_value=32'(p.wl_ck)+32'(p.dram_ck_twr)+8+32'(p.dram_ck_trp_ab)+32'(p.dram_ck_trfc_ab)
      +(32'(p.wck_twck_dis)+3)/(p.ratio==2 ? 2 : 4)+8;
    if(reserve_value<32'(p.dram_ck_tras_min)+32'(p.dram_ck_trp_ab)+32'(p.dram_ck_trfc_ab)+8)
      reserve_value=32'(p.dram_ck_tras_min)+32'(p.dram_ck_trp_ab)+32'(p.dram_ck_trfc_ab)+8;
    if(per_bank) reserve_value=reserve_value-32'(p.dram_ck_trfc_ab)+32'(p.dram_ck_trfc_pb)
      +7*32'(p.dram_ck_tpbr2pbr)+16*32'(p.dram_ck_tppd);
    return reserve_value;
  endfunction
  function automatic logic [31:0] register_service_budget(input lpddr5_mc_profile_t p);
    logic unused_profile;
    unused_profile=^p;
    return 32'(p.rl_ck)+32'(p.management_ck_tctrl_delay)
      +(32'(p.dfi_wck_tphy_rdlat)+32'(p.wck_twck_dis)+7)/(p.ratio==2 ? 2 : 4)
      +32'(p.dram_ck_tmrr)+32'(p.dram_ck_tmrw)+16;
  endfunction
  function automatic logic [31:0] fsp_admission_budget(input lpddr5_mc_profile_t p);
    logic [31:0] spacing, guard_time;
    logic unused_profile;
    unused_profile=^p;
    spacing=p.dram_ck_tmrd>p.dram_ck_tmrw ? 32'(p.dram_ck_tmrd) : 32'(p.dram_ck_tmrw);
    guard_time=p.dram_ck_tfc>201 ? 32'(p.dram_ck_tfc) : 32'd201;
    return 19*(spacing+2)+guard_time+6+32'(p.management_ck_tinit_complete)+32'(p.management_ck_tinit_start)+8;
  endfunction
  function automatic logic [31:0] update_admission_budget(input lpddr5_mc_profile_t p,
      input logic phy_request, input logic [1:0] phy_type);
    logic unused_profile;
    unused_profile=^p;
    if(!phy_request) return 32'(p.management_ck_tctrlupd_max)+2;
    case(phy_type)
      0: return 32'(p.management_ck_tphyupd_type0)+2;
      1: return 32'(p.management_ck_tphyupd_type1)+2;
      2: return 32'(p.management_ck_tphyupd_type2)+2;
      default: return 32'(p.management_ck_tphyupd_type3)+2;
    endcase
  endfunction
  function automatic logic [31:0] config_crc(input lpddr5_mc_channel_config_t cfg);
    logic [$bits(lpddr5_mc_channel_config_t)-1:0] bits_value;
    logic [31:0] crc;
    bits_value = cfg; crc = '1;
    for (int i=0; i<$bits(lpddr5_mc_channel_config_t); i++) begin
      if (crc[0] ^ bits_value[i]) crc = (crc >> 1) ^ 32'hedb88320;
      else crc = crc >> 1;
    end
    return ~crc;
  endfunction

