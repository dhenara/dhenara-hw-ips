"""Reset dispatch measures real recovery traffic after an idle observed prefix.

Only external tool processes are substituted. Source/pin/WCK replay and finite
cost accounting execute on synthetic traces generated by independent fixtures.
"""

import contextlib
import importlib.util
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from cap_granule_runner_test import trace
from system.host import Violation
from workload_costs import measure

SPEC = importlib.util.spec_from_file_location("reset_integration_runner", Path(__file__).with_name("check.py"))
runner = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(runner)


def idle(events):
    """Retain two real idle samples per channel and a complete trace tail."""
    return (
        events[:1]
        + [
            dict(e, cs=0, ca=0, wck=0, write=0, read=0, **{"return": 0})
            for e in events
            if e["kind"] == "phy" and e["ck"] < 2
        ]
        + [{"kind": "end", "ps": 2500}]
    )


class ResetRunnerTests(unittest.TestCase):
    def invoke(self, selection, *, recovery="valid"):
        with tempfile.TemporaryDirectory(dir=os.environ["DHENARA_AGENT_TOOL_STORAGE_ROOT"]) as temporary:
            root = Path(temporary)
            report = root / "proof/report.json"
            events = trace(64)
            events = events[:1] + sorted(events[1:], key=lambda e: e["ps"])
            prefix = events if not selection else idle(events)
            recovered = idle(events) if recovery == "empty" else events
            if recovery == "bad-data":
                recovered = [dict(e, data=e["data"] ^ 1) if e["kind"] == "r" else e for e in recovered]
            if recovery == "missing-tail":
                recovered = recovered[:-1]
            argv = ["check.py", "--family", "controller", "--report", str(report), "--build-name", "synthetic-reset"]
            argv += selection
            commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=runner.REPO, text=True)

            def source_observation(command, **kwargs):
                if command == ["git", "rev-parse", "HEAD"]:
                    return commit
                if command == ["git", "status", "--porcelain"]:
                    return ""
                raise AssertionError(f"Unexpected source observation: {command}")

            def process(command, **kwargs):
                if Path(command[0]).name == "Vcontroller_tb":
                    for name, records in (("observations.jsonl", prefix), ("recovery-observations.jsonl", recovered)):
                        report.with_name(name).write_text("".join(json.dumps(e) + "\n" for e in records))
                    kwargs["stdout"].write("CONTROLLER_INTEGRATION_PASS\n")
                elif Path(command[0]).name != "verilator" and command[1:3] != ["-m", "unittest"]:
                    raise AssertionError(f"Unexpected external command: {command}")
                return subprocess.CompletedProcess(command, 0)

            error = None
            with (
                patch.object(sys, "argv", argv),
                patch.object(sys, "pycache_prefix", sys.pycache_prefix),
                patch.dict(os.environ, DHENARA_AGENT_TOOL_STORAGE_ROOT=temporary),
                patch.object(subprocess, "check_output", side_effect=source_observation),
                patch.object(subprocess, "run", side_effect=process),
                patch("workload_costs.measure", wraps=measure) as accounting,
                contextlib.redirect_stdout(io.StringIO()),
            ):
                try:
                    runner.main()
                except Violation as caught:
                    error = caught
            return json.loads(report.read_text()), [call.args[0].name for call in accounting.call_args_list], error

    def test_each_reset_selection_measures_recovery_without_empty_prefix(self):
        for selection in (["--runtime-reset"], ["--runtime-reset-matrix"], ["--runtime-reset-case", "9"]):
            with self.subTest(selection=selection):
                report, calls, error = self.invoke(selection)
                self.assertIsNone(error)
                self.assertEqual(report["status"], "passed")
                self.assertNotIn("workload_costs", report)
                self.assertEqual(calls, ["recovery-observations.jsonl"])
                for direction in ("read", "write"):
                    self.assertEqual(report["external_observations"][direction + "_bytes"], 0)
                    self.assertEqual(report["recovered_external_observations"][direction + "_bytes"], 128)
                    self.assertEqual(report["recovered_workload_costs"][direction]["successful_payload_bytes"], 128)
                    self.assertEqual(report["recovered_workload_costs"][direction]["completed_transactions"], 2)

    def test_empty_recovery_still_fails_cost_accounting(self):
        report, calls, error = self.invoke(["--runtime-reset-matrix"], recovery="empty")
        self.assertRegex(str(error), "workload missing interval/tail")
        self.assertEqual(report["status"], "failed")
        self.assertEqual(calls, ["recovery-observations.jsonl"])
        self.assertIn("recovered_external_observations", report)
        self.assertNotIn("recovered_workload_costs", report)

    def test_corrupt_or_unclosed_recovery_still_fails_physical_replay(self):
        for recovery in ("bad-data", "missing-tail"):
            with self.subTest(recovery=recovery):
                report, calls, error = self.invoke(["--runtime-reset"], recovery=recovery)
                self.assertIsInstance(error, Violation)
                self.assertEqual(report["status"], "failed")
                self.assertEqual(calls, [])

    def test_ordinary_controller_measures_both_traffic_segments(self):
        report, calls, error = self.invoke([])
        self.assertIsNone(error)
        self.assertEqual(report["status"], "passed")
        self.assertEqual(calls, ["observations.jsonl", "recovery-observations.jsonl"])
        self.assertEqual(report["workload_costs"], report["recovered_workload_costs"])


if __name__ == "__main__":
    unittest.main()
